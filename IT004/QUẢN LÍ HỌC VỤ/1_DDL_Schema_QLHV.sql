CREATE TRIGGER HOCVITRGKHOA
ON KHOA
AFTER INSERT, UPDATE
AS
BEGIN
    IF EXISTS (
        SELECT 1
        FROM KHOA K
        JOIN GIAOVIEN GV ON K.TRGKHOA = GV.MAGV
        WHERE GV.MAKHOA <> K.MAKHOA
           OR GV.HOCVI NOT IN ('TS', 'PTS')
    )
    BEGIN
        ROLLBACK TRANSACTION;
    END
END;
GO

