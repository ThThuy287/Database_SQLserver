-- CAU 22
SELECT MH.MAMH, 
		SUM(CASE WHEN KQ.KQUA = 'Dat' THEN 1 ELSE 0 END) AS SL_DAT,
		SUM(CASE WHEN KQ.KQUA = 'Khong Dat' THEN 1 ELSE 0 END) AS SL_KDAT
FROM MONHOC MH
JOIN KETQUATHI KQ ON KQ.MAMH = MH.MAMH
GROUP BY MH.MAMH
GO

-- CAU 23
SELECT GV.MAGV, GV. HOTEN FROM GIAOVIEN GV
JOIN LOP L ON L.MAGVCN = GV.MAGV
JOIN GIANGDAY GD ON GD.MAGV = L.MAGVCN
WHERE GD.MALOP = L.MALOP
GROUP BY GV.MAGV, GV. HOTEN
HAVING COUNT(GD.MALOP) >= 1;
GO

-- CAU 24
SELECT TOP 1 WITH TIES HV.HO, HV.TEN FROM HOCVIEN HV
JOIN LOP L ON L.TRGLOP = HV.MAHV
ORDER BY L.SISO DESC;
GO

-- CAU 25
SELECT HV.HO, HV.TEN FROM HOCVIEN HV
JOIN LOP L ON L.TRGLOP = HV.MAHV
JOIN (
	SELECT HV1.MAHV, KQ1.MAMH FROM KETQUATHI KQ1
	JOIN HOCVIEN HV1 ON HV1.MAHV = KQ1.MAHV
	GROUP BY HV1.MAHV, KQ1.MAMH
	HAVING SUM(CASE WHEN KQ1.KQUA = 'Khong Dat' THEN 0 ELSE 1 END) = 0) AS ROT 
ON ROT.MAHV = L.TRGLOP
GROUP BY HV.HO, HV.TEN, HV.MAHV
HAVING COUNT(ROT.MAMH) > 3;
GO

-- CAU 26
SELECT TOP 1 WITH TIES HV.MAHV, HV.HO, HV.TEN FROM HOCVIEN HV
JOIN KETQUATHI KQ ON KQ.MAHV = HV.MAHV
WHERE KQ.DIEM = 9 OR KQ.DIEM = 10
GROUP BY HV.MAHV, HV.HO, HV.TEN
ORDER BY COUNT(KQ.MAMH) DESC;
GO

-- CAU 27
SELECT MALOP, MAHV, TEN, HO FROM (
	SELECT HV.MALOP, HV.MAHV, HV.HO, HV.TEN,
	DENSE_RANK() OVER (PARTITION BY HV.MALOP ORDER BY COUNT(*) DESC) AS XEPHANG
	FROM HOCVIEN HV
	JOIN KETQUATHI KQ ON KQ.MAHV = HV.MAHV
	WHERE KQ.DIEM >= 9
	GROUP BY HV.MALOP, HV.MAHV, HV.HO, HV.TEN ) AS BANGXEPHANG
WHERE XEPHANG = 1;
GO

-- CAU 28
SELECT GD.HOCKY, GD.NAM , GD.MAGV, COUNT(GD.MALOP) AS TONG_LOP, COUNT(GD.MAMH) AS TONG_MH
FROM GIANGDAY GD
GROUP BY GD.HOCKY, GD.NAM , GD.MAGV;
GO

-- CAU 29
SELECT HOCKY, NAM, MAGV, HOTEN FROM (
	SELECT GD1.HOCKY, GD1.NAM, GD1.MAGV, GV1.HOTEN,
	DENSE_RANK() OVER (PARTITION BY GD1.HOCKY, GD1.NAM ORDER BY COUNT(*) DESC) AS XEPHANG
	FROM GIANGDAY GD1
	JOIN GIAOVIEN GV1 ON GV1.MAGV = GD1.MAGV
	GROUP BY GD1.HOCKY, GD1.NAM, GD1.MAGV, GV1.HOTEN) AS BANGXEPHANG
WHERE XEPHANG = 1;
GO

-- CAU 30
SELECT TOP 1 WITH TIES MAMH, TENMH FROM (
	SELECT MH.MAMH, MH.TENMH, COUNT(KQ.MAHV) AS SL
	FROM MONHOC MH
	JOIN KETQUATHI KQ ON KQ.MAMH = MH.MAMH
	WHERE KQ.LANTHI = 1 AND KQ.KQUA = 'Khong Dat'
	GROUP BY MH.MAMH, MH.TENMH) AS TH
ORDER BY SL DESC;
GO

-- CAU 31
SELECT KQ.MAHV, HV.HO, HV.TEN FROM KETQUATHI KQ
JOIN HOCVIEN HV ON HV.MAHV = KQ.MAHV
WHERE KQ.LANTHI = 1
GROUP BY KQ.MAHV, HV.HO, HV.TEN
HAVING SUM(CASE WHEN KQ.KQUA = 'Dat' THEN 0 ELSE 1 END) = 0;
GO

-- CAU 32
SELECT KQ.MAHV, HV.HO, HV.TEN FROM KETQUATHI KQ
JOIN HOCVIEN HV ON HV.MAHV = KQ.MAHV
WHERE KQ.LANTHI = (
	SELECT MAX(KQ1.LANTHI) FROM KETQUATHI KQ1
	WHERE KQ.MAHV = KQ1.MAHV AND KQ.MAMH = KQ1.MAMH )
GROUP BY KQ.MAHV, HV.HO, HV.TEN
HAVING SUM(CASE WHEN KQ.KQUA = 'Dat' THEN 0 ELSE 1 END) = 0;
GO

-- CAU 33
SELECT HV.MAHV, HV.HO, HV.TEN FROM HOCVIEN HV
JOIN (
	SELECT HV1.MAHV FROM HOCVIEN HV1
	WHERE NOT EXISTS (
		SELECT MH1.MAMH FROM MONHOC MH1
		WHERE NOT EXISTS (
			SELECT KQ1.MAMH, KQ1.MAHV FROM KETQUATHI KQ1
			WHERE KQ1.MAHV = HV1.MAHV AND KQ1.MAMH = MH1.MAMH
		)
	)
) AS SV ON SV.MAHV = HV.MAHV
JOIN KETQUATHI KQ ON KQ.MAHV = SV.MAHV
WHERE KQ.LANTHI = 1
GROUP BY HV.MAHV, HV.HO, HV.TEN
HAVING SUM(CASE WHEN KQ.KQUA = 'Dat' THEN 0 ELSE 1 END) = 0;
GO

-- CAU 34
SELECT HV.MAHV, HV.HO, HV.TEN FROM HOCVIEN HV
JOIN (
	SELECT HV1.MAHV FROM HOCVIEN HV1
	WHERE NOT EXISTS (
		SELECT MH1.MAMH FROM MONHOC MH1
		WHERE NOT EXISTS (
			SELECT KQ1.MAMH, KQ1.MAHV FROM KETQUATHI KQ1
			WHERE KQ1.MAHV = HV1.MAHV AND KQ1.MAMH = MH1.MAMH
		)
	)
) AS SV ON SV.MAHV = HV.MAHV
JOIN KETQUATHI KQ ON KQ.MAHV = SV.MAHV
WHERE KQ.LANTHI = (
	SELECT MAX(KQ2.LANTHI) FROM KETQUATHI KQ2
	WHERE KQ2.MAHV = KQ.MAHV AND KQ2.MAMH = KQ.MAMH
	)
GROUP BY HV.MAHV, HV.HO, HV.TEN
HAVING SUM(CASE WHEN KQ.KQUA = 'Dat' THEN 0 ELSE 1 END) = 0;
GO

-- CAU 35
SELECT HV.MAMH, HV.MAHV, HV.HO, HV.TEN FROM (
	SELECT KQ1.MAMH, KQ1.MAHV, HV1.HO, HV1.TEN,
	DENSE_RANK() OVER (PARTITION BY KQ1.MAMH ORDER BY KQ1.DIEM DESC) AS XEPHANG
	FROM HOCVIEN HV1
	JOIN KETQUATHI KQ1 ON KQ1.MAHV = HV1.MAHV
	WHERE KQ1.LANTHI = (
		SELECT MAX(KQ2.LANTHI) FROM KETQUATHI KQ2
		WHERE KQ2.MAHV = KQ1.MAHV AND KQ2.MAMH = KQ1.MAMH
	)
) AS HV
WHERE XEPHANG = 1;
GO

