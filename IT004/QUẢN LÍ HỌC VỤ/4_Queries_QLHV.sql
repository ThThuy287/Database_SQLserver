-- CAU 15
SELECT HV.HO, HV.TEN
FROM HOCVIEN HV
JOIN KETQUATHI KQ ON KQ.MAHV = HV.MAHV
WHERE HV.MALOP = 'K11'
  AND (
        (KQ.LANTHI > 3 AND KQ.KQUA = 'Khong Dat')
        OR
        (KQ.LANTHI = 2 AND KQ.DIEM = 5 AND KQ.MAMH = 'CTRR')
      );
GO

-- CAU 16
