CREATE TRIGGER CHECK_NGAYTHI
ON KETQUATHI
AFTER INSERT, UPDATE
AS BEGIN
	IF EXISTS (
		SELECT * FROM INSERTED I 
		JOIN KETQUATHI KQ ON KQ.MAHV = I.MAHV AND KQ.MAMH = I.MAMH AND KQ.LANTHI = I.LANTHI - 1
		WHERE I.NGTHI <= KQ.NGTHI
	)
	BEGIN 
		RAISERROR('Ngay thi sau phai lon hon ngay thi truoc',16,1)
		ROLLBACK
	END
END;
GO

-- CAU 22
CREATE TRIGGER CHECK_MHTRC
ON GIANGDAY
AFTER INSERT, UPDATE
AS BEGIN
	IF EXISTS (
		SELECT * FROM INSERTED I
		JOIN DIEUKIEN DK ON DK.MAMH = I.MAMH
		WHERE NOT EXISTS (
			SELECT * FROM GIANGDAY GD
			WHERE GD.MALOP = I.MALOP AND GD.MAMH = DK.MAMH_TRUOC AND GD.DENNGAY < I.TUNGNGAY
		)
	) 
	BEGIN 
		RAISERROR('Phai hoc mon tien quyet truoc',16,1)
		ROLLBACK
	END
END;
GO

