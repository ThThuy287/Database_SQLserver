-- CAU 9
CREATE TRIGGER CHECK_TRGLOP
ON LOP
AFTER INSERT, UPDATE
AS BEGIN
	IF EXISTS (
		SELECT * FROM INSERTED I
		JOIN HOCVIEN HV ON HV.MALOP = I.MALOP
		WHERE I.TRGLOP <> HV.MAHV
	)
	BEGIN
		RAISERROR ('TRGLOP phai la hoc vien cua Lop do',16,1)
		ROLLBACK
	END
END;
GO

-- CAU 10
CREATE TRIGGER CHECK_TRGKHOA
ON KHOA
AFTER INSERT, UPDATE
AS BEGIN
	IF EXISTS (
		SELECT * FROM INSERTED I
		JOIN GIAOVIEN GV ON GV.MAGV = I.TRGKHOA
		WHERE I.MAKHOA <> GV.MAKHOA OR GV.HOCVI NOT IN ('TS', 'PTS')
	)
	BEGIN 
		RAISERROR('TRGKHOA phai la giao vien thuoc khoa do va co hoc vi TS hoac PTS',16,1)
		ROLLBACK
	END
END;
GO

-- CAU 15
CREATE TRIGGER CHECK_THI
ON KETQUATHI 
AFTER INSERT, UPDATE
AS BEGIN
	IF EXISTS (
		SELECT * FROM INSERTED I
		JOIN HOCVIEN HV ON HV.MAHV = I.MAHV
		JOIN GIANGDAY GD ON GD.MALOP = HV.MALOP AND GD.MAMH = I.MAMH
		WHERE GD.DENNGAY > I.NGTHI 
	) 
	BEGIN
		RAISERROR('Hoc vien chi duoc thi khi lop da hoc xong mon nay',16,1)
		ROLLBACK
	END
END;
GO

-- CAU 16
CREATE TRIGGER CHECK_MH
ON GIANGDAY
AFTER INSERT, UPDATE
AS BEGIN 
	IF EXISTS (
		SELECT G.HOCKY, G.NAM, G.MALOP FROM GIANGDAY G
		JOIN INSERTED I ON I.HOCKY = G.HOCKY AND I.NAM = G.NAM AND I.MALOP = G.MALOP
		GROUP BY G.HOCKY, G.NAM, G.MALOP
		HAVING COUNT(G.MAMH) > 3
	)
	BEGIN
		RAISERROR('Moi hoc ky cua tung nam moi lop hoc toi da 3 mon',16,1)
		ROLLBACK
	END
END;
GO

-- CAU 17
CREATE TRIGGER CHECK_SISO
ON HOCVIEN 
AFTER INSERT, UPDATE, DELETE
AS BEGIN 
	UPDATE LOP 
	SET SISO = ISNULL ((
		SELECT COUNT(HV.MAHV) FROM HOCVIEN HV 
		WHERE LOP.MALOP = HV.MALOP
	), 0) 
	WHERE MALOP IN (
		SELECT MALOP FROM INSERTED 
		UNION
		SELECT MALOP FROM DELETED
	)
END;
GO

