CREATE TRIGGER CHECK_MUCLUONG
ON GIAOVIEN
AFTER INSERT, UPDATE 
AS BEGIN
	IF EXISTS (
		SELECT GV.HOCVI, GV.HOCHAM, GV.HESO FROM GIAOVIEN GV
		JOIN INSERTED I ON I.HOCVI = GV.HOCVI AND I.HOCHAM = GV.HOCHAM AND I.HESO = GV.HESO
		GROUP BY GV.HOCVI, GV.HOCHAM, GV.HESO
		HAVING COUNT(DISTINCT GV.MUCLUONG) > 1
	) 
	BEGIN
		RAISERROR('GV cung hoc ham, hoc vi, he so thi muc luong bang nhau',16,1)
		ROLLBACK
	END
END;
GO

-- CAU 20
CREATE TRIGGER CHECK_THILAI
ON KETQUATHI
AFTER INSERT, UPDATE
AS BEGIN
	IF EXISTS (
	SELECT * FROM INSERTED I 
	JOIN KETQUATHI KQ ON KQ.MAHV = I.MAHV AND KQ.LANTHI = I.LANTHI - 1 AND KQ.MAMH = I.MAMH
	WHERE I.LANTHI > 1 AND KQ.DIEM >= 5
	)
	BEGIN 
		RAISERROR('Hoc vien chi duoc thi lai khi diem duoi 5',16,1)
		ROLLBACK
	END
END;
GO

