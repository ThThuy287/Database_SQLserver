CREATE TRIGGER GIANG_DAY
ON GIANGDAY
AFTER INSERT, UPDATE
AS BEGIN
	IF EXISTS (
		SELECT * FROM INSERTED I
		JOIN GIAOVIEN GV ON GV.MAGV = I.MAGV
		JOIN MONHOC MH ON MH.MAMH = I.MAMH
		WHERE MH.MAKHOA <> GV.MAKHOA
	)
	BEGIN
		RAISERROR('GV day mon thuoc khoa gv phu trach',16,1)
		ROLLBACK
	END
END;
GO
