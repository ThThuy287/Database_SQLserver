-- CAU 18
SELECT DISTINCT CTHD.SOHD FROM CTHD
WHERE NOT EXISTS (
	SELECT MASP
	FROM SANPHAM
	WHERE NOT EXISTS (
		SELECT SOHD, MASP
		FROM CTHD
		)
	);
GO

