-- CAU 6
SELECT SOHD, TRIGIA FROM HOADON
WHERE NGHD = '01/01/2007' OR NGHD = '02/01/2007';
GO

-- CAU 7
SELECT SOHD, TRIGIA FROM HOADON
WHERE NGHD >= '01/01/2007' AND NGHD < '01/02/2007'
ORDER BY NGHD ASC, TRIGIA DESC;
GO

-- CAU 8 
SELECT DISTINCT KHACHHANG.MAKH, KHACHHANG.HOTEN FROM KHACHHANG
JOIN HOADON ON KHACHHANG.MAKH = HOADON.MAKH
WHERE HOADON.NGHD = '01/01/2007';
GO

-- CAU 9 
SELECT SOHD, TRIGIA FROM HOADON
JOIN NHANVIEN ON HOADON.MANV = NHANVIEN.MANV
WHERE NHANVIEN.HOTEN = 'Nguyen Van B' AND HOADON.NGHD = '28/10/2006';
GO

-- CAU 10
SELECT DISTINCT SANPHAM.MASP, SANPHAM.TENSP FROM SANPHAM
JOIN CTHD ON SANPHAM.MASP = CTHD.MASP
JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
JOIN KHACHHANG ON HOADON.MAKH = KHACHHANG.MAKH
WHERE KHACHHANG.HOTEN = 'Nguyen Van A' AND HOADON.NGHD >= '01/10/2006' AND HOADON.NGHD < '01/11/2006';
GO

-- CAU 11
SELECT HOADON.SOHD FROM HOADON
JOIN CTHD ON HOADON.SOHD = CTHD.SOHD
WHERE CTHD.MASP = 'BB01' OR CTHD.MASP = 'BB02';
GO

