GO

-- CAU 33
SELECT DISTINCT NUOCSX, MAX(SP.GIA) AS CAO_NHAT,
				MIN(SP.GIA) AS THAP_NHAT, AVG(SP.GIA) AS TRUNG_BINH
FROM SANPHAM SP
GROUP BY NUOCSX;
GO

-- CAU 34
SELECT NGHD, SUM(TRIGIA) AS TONG_DOANHTHU
FROM HOADON 
GROUP BY NGHD;
GO

-- CAU 35
SELECT CT.MASP, SUM(CT.SL) AS TONG_SL
FROM CTHD CT
JOIN HOADON HD ON HD.SOHD = CT.SOHD
WHERE MONTH(HD.NGHD) = 10 AND YEAR(HD.NGHD) = 2006
GROUP BY CT.MASP;
GO

-- CAU 36
SELECT MONTH(HD.NGHD) AS THANG, SUM(HD.TRIGIA) AS TONG_DOANHTHU
FROM HOADON HD
WHERE YEAR(HD.NGHD) = 2006
GROUP BY MONTH(HD.NGHD);
GO

-- CAU 37
SELECT CT.SOHD, COUNT(CT.MASP) AS SO_SP
FROM CTHD CT
GROUP BY CT.SOHD
HAVING COUNT(CT.MASP) >=4;
GO

-- CAU 38
SELECT CT.SOHD
FROM CTHD CT
JOIN SANPHAM SP ON SP.MASP = CT.MASP
WHERE SP.NUOCSX = 'Viet Nam'
GROUP BY CT.SOHD
HAVING COUNT(DISTINCT CT.MASP) = 3;
GO

-- CAU 39
SELECT TOP 1 WITH TIES HD.MAKH, KH.HOTEN, COUNT(HD.SOHD) AS SOLANMUA
FROM HOADON HD
JOIN KHACHHANG KH ON KH.MAKH = HD.MAKH
GROUP BY HD.MAKH, KH.HOTEN
ORDER BY COUNT(HD.SOHD) DESC;
GO

-- CAU 40
SELECT TOP 1 WITH TIES MONTH(NGHD) AS THANG, SUM(TRIGIA) AS DOANH_SO
FROM HOADON 
WHERE YEAR(NGHD) = 2006
GROUP BY MONTH(NGHD)
ORDER BY SUM(TRIGIA) DESC;
GO

-- CAU 41
SELECT TOP 1 WITH TIES CT.MASP, SP.TENSP, SUM(CT.SL) AS TONG_SP
FROM CTHD CT
JOIN SANPHAM SP ON SP.MASP = CT.MASP
JOIN HOADON HD ON HD.SOHD = CT.SOHD
WHERE YEAR(HD.NGHD) = 2006
GROUP BY CT.MASP, SP.TENSP
ORDER BY SUM(CT.SL) ASC;
GO

-- CAU 42
SELECT SP.NUOCSX, SP.MASP, SP.TENSP, SP.GIA
FROM SANPHAM SP
WHERE SP.GIA = (
	SELECT MAX(SP1.GIA) FROM SANPHAM SP1
	WHERE SP.NUOCSX = SP1.NUOCSX );
GO

-- CAU 43
SELECT SP.NUOCSX FROM SANPHAM SP 
GROUP BY SP.NUOCSX
HAVING COUNT(DISTINCT SP.GIA) >= 3;
GO

-- CAU 44
SELECT TOP 1 WITH TIES KH.MAKH, KH.HOTEN FROM (
	SELECT TOP 10 WITH TIES KH1.MAKH, KH1.HOTEN FROM KHACHHANG KH1
	JOIN HOADON HD1 ON HD1.MAKH = KH1.MAKH
	GROUP BY KH1.MAKH, KH1.HOTEN
	ORDER BY SUM(HD1.TRIGIA) DESC) AS KH
JOIN HOADON HD ON HD.MAKH = KH.MAKH
GROUP BY KH.MAKH, KH.HOTEN
ORDER BY COUNT(HD.SOHD) DESC;
GO
