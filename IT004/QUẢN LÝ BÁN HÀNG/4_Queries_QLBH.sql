-- CAU 19
SELECT COUNT(HD.SOHD) AS SO_HD_KHONGDK
FROM HOADON HD
LEFT JOIN KHACHHANG KH ON KH.MAKH = HD.MAKH
WHERE KH.NGDK IS NULL OR HD.MAKH IS NULL;
GO

-- CAU 20
SELECT COUNT(DISTINCT CT.MASP) AS SO_SP
FROM CTHD CT
JOIN HOADON HD ON HD.SOHD = CT.SOHD
WHERE YEAR(HD.NGHD) = 2006;
GO

-- CAU 21
SELECT MAX(HD.TRIGIA) AS CAONHAT, MIN (HD.TRIGIA) AS THAPNHAP
FROM HOADON HD;
GO

-- CAU 22
SELECT AVG(HD.TRIGIA) AS TRUNGBINH 
FROM HOADON HD
WHERE YEAR(HD.NGHD) = 2006;
GO

-- CAU 23
SELECT SUM(HD.TRIGIA) AS TONG 
FROM HOADON HD
WHERE YEAR(HD.NGHD) = 2006;
GO

-- CAU 24
SELECT MAX(HD.TRIGIA) AS CAONHAT 
FROM HOADON HD
WHERE YEAR(HD.NGHD) = 2006;
GO

-- CAU 25
SELECT KH.HOTEN FROM KHACHHANG KH
JOIN HOADON HD ON HD.MAKH = KH.MAKH
WHERE YEAR(HD.NGHD) = 2006 AND HD.TRIGIA = (
	SELECT MAX(HD1.TRIGIA) FROM HOADON HD1);
GO

-- CAU 26
SELECT TOP 3 WITH TIES MAKH, HOTEN FROM KHACHHANG
ORDER BY DOANHSO DESC;
GO

-- CAU 27
SELECT DISTINCT MASP, TENSP FROM SANPHAM
WHERE GIA IN (
	SELECT TOP 3 GIA FROM SANPHAM
	ORDER BY GIA DESC);
GO

-- CAU 28
SELECT DISTINCT MASP, TENSP FROM SANPHAM
WHERE NUOCSX = 'Thai Lan' AND GIA IN (
	SELECT TOP 3 GIA FROM SANPHAM
	ORDER BY GIA DESC);
GO

-- CAU 29
SELECT DISTINCT MASP, TENSP FROM SANPHAM
WHERE NUOCSX = 'Trung Quoc' AND GIA IN (
	SELECT TOP 3 GIA FROM SANPHAM
	WHERE NUOCSX = 'Trung Quoc'
	ORDER BY GIA DESC);
GO

--- CAU 30
SELECT * FROM (
	SELECT MAKH, HOTEN, DOANHSO,
	RANK() OVER (ORDER BY DOANHSO DESC) AS THUHANG
	FROM KHACHHANG )
	AS BANGXEPHANG
WHERE THUHANG <= 3;
GO

-- CAU 31
