WHERE NUOCSX = 'Trung Quoc' AND GIA BETWEEN 30000 AND 40000;
GO

-- CAU 5
SELECT MASP, TENSP FROM SANPHAM 
WHERE NUOCSX = 'Trung Quoc' OR NUOCSX = 'Thai Lan' AND GIA BETWEEN 30000 AND 40000;
