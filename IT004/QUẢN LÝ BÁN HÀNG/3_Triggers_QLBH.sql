-- CAU 11
CREATE TRIGGER CHECK_NGHD_NGDK
ON HOADON 
AFTER INSERT, UPDATE 
AS BEGIN
	IF EXISTS (
		SELECT * FROM INSERTED I
		JOIN KHACHHANG KH ON KH.MAKH = I.MAKH
		WHERE I.NGHD < KH.NGDK )
	BEGIN 
		RAISERROR ('NGHD lon hon hoac bang NGDK', 16, 1)
		ROLLBACK
	END
END;
GO

-- CAU 12
CREATE TRIGGER CHECK_NGHD_NGVL
ON HOADON
AFTER INSERT, UPDATE
AS BEGIN
	IF EXISTS (
		SELECT * FROM INSERTED I 
		JOIN NHANVIEN NV ON NV.MANV = I.MANV
		WHERE I.NGHD < NV.NGVL
	)
	BEGIN
		RAISERROR ('NGHD lon hoac bang NGVL',16,1)
		ROLLBACK
	END
END;
GO

-- CAU 13
CREATE TRIGGER UPDATE_TRIGIA
ON CTHD
AFTER INSERT, UPDATE, DELETE
AS BEGIN
	UPDATE HOADON
	SET TRIGIA = ISNULL((
		SELECT SUM(CT.SL * SP.GIA)
		FROM CTHD CT
		JOIN SANPHAM SP ON SP.MASP = CT.MASP
		WHERE CT.SOHD = HOADON.SOHD
	), 0)
	WHERE SOHD IN (
		SELECT SOHD FROM INSERTED 
		UNION
		SELECT SOHD FROM DELETED
	)
END;
GO

-- CAU 14
CREATE TRIGGER CHECK_DOANHSO
ON HOADON
AFTER UPDATE, INSERT, DELETE 
AS BEGIN 
	UPDATE KHACHHANG
	SET DOANHSO = ISNULL ((
		SELECT SUM(HD.TRIGIA) FROM HOADON HD
		WHERE KHACHHANG.MAKH = HD.MAKH
		), 0)
	WHERE MAKH IN (
		SELECT MAKH FROM INSERTED
		UNION 
		SELECT MAKH FROM DELETED
	)
END;
GO
